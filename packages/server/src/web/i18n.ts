export const messages: Record<Lang, Record<MessageKey, string>> = { en, 'pt-BR': ptBR };

/** The message for a key, with {name} placeholders filled in. An unknown placeholder is left as is. */
export function t(lang: Lang, key: MessageKey, params: Record<string, string> = {}): string {
  return messages[lang][key].replace(/\{(\w+)\}/g, (whole, name: string) => params[name] ?? whole);
}

export function fromTag(tag: string | null | undefined): Lang | undefined {
  const lower = tag?.trim().toLowerCase();
  if (!lower) return undefined;
  if (lower === 'pt' || lower.startsWith('pt-')) return 'pt-BR';
  if (lower === 'en' || lower.startsWith('en-')) return 'en';
  return undefined;
}

/**
 * The language of a page: an explicit ?lang= wins, then the browser's Accept-Language by quality,
 * then English. Anything unrecognised falls through to the next rule instead of being an error.
 */
export function pickLang(requested: string | null | undefined, acceptLanguage?: string): Lang {
  const explicit = fromTag(requested);
  if (explicit) return explicit;
  if (acceptLanguage) {
    const ranked = acceptLanguage
      .split(',')
      .slice(0, 20)
      .map((part) => {
        const [tag = '', ...params] = part.split(';');
        const quality = params
          .map((param) => /^\s*q=([0-9.]+)\s*$/i.exec(param)?.[1])
          .find((value) => value !== undefined);
        return { tag, quality: quality === undefined ? 1 : Number(quality) };
      })
      .filter((entry) => entry.quality > 0)
      .sort((a, b) => b.quality - a.quality);
    for (const { tag } of ranked) {
      const lang = fromTag(tag);
      if (lang) return lang;
    }
  }
  return 'en';
}

// The core writes its validation errors in English. They reach the owner's form, so Portuguese
// gets a translation; anything not listed here is shown as the core wrote it.
const PT_FORM_ERRORS: [RegExp, (match: RegExpExecArray) => string][] = [
  [
    /^invalid amount/i,
    () => 'Valor inválido. Use apenas números, com ponto nos centavos, como 1250.50.',
  ],
  [
    /^too many decimal places \(max (\d+)\)/i,
    (match) => `Casas decimais demais: o máximo permitido é ${match[1]}.`,
  ],
  [/^amount must be greater than zero/i, () => 'O valor deve ser maior que zero.'],
  [/^amount is too large/i, () => 'O valor é grande demais.'],
  [/^client name is required/i, () => 'Informe o nome do cliente.'],
  [/^client name is too long/i, () => 'O nome do cliente é longo demais.'],
  [/^description is required/i, () => 'Informe a descrição.'],
  [/^description is too long/i, () => 'A descrição é longa demais.'],
  [/^due date must be in the future/i, () => 'O vencimento deve ser uma data futura.'],
  [/^unsupported asset/i, () => 'Este token não é aceito.'],
];

/** A validation error as the owner should read it: translated for Portuguese, as written otherwise. */
export function formError(lang: Lang, message: string): string {
  if (lang === 'pt-BR') {
    for (const [pattern, translate] of PT_FORM_ERRORS) {
      const match = pattern.exec(message);
      if (match) return translate(match);
    }
  }
  return message.charAt(0).toUpperCase() + message.slice(1);
}
